export const getLanguage = () => language;
export function t(text, values = {}) {
  const dictionary = language === 'es' ? spanish : language === 'zh-Hant' ? translations : {};
  let result = dictionary[text] ?? text;
  for (const [key, value] of Object.entries(values)) result = result.replaceAll(`{${key}}`, value);
  return result;
}
const originals = new WeakMap();
function translatePage() {
  document.documentElement.lang = language;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest('script, style, #catalog, #bag-items, #bag-status, #messages .user, #messages .assistant:not([data-greeting]), [data-language-option]')) continue;
    if (!originals.has(node)) originals.set(node, node.textContent);
    const original = originals.get(node);
    const trimmed = original.trim();
    if (translations[trimmed]) node.textContent = original.replace(trimmed, t(trimmed));
  }
  document.querySelectorAll('[aria-label], [alt], [placeholder]').forEach(element => {
    if (element.closest('#catalog, #bag-items')) return;
    let attrs = originals.get(element);
    if (!attrs) { attrs = {}; originals.set(element, attrs); }
    for (const attr of ['aria-label', 'alt', 'placeholder']) {
      if (!element.hasAttribute(attr)) continue;
      attrs[attr] ??= element.getAttribute(attr);
      element.setAttribute(attr, t(attrs[attr]));
    }
  });
  document.querySelector('#language-select').value = language;
}
translatePage();
